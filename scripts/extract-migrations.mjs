#!/usr/bin/env node
/**
 * Generates the browser mock's committed migration snapshot from Mini's SQL
 * files. Run after adding or changing a file in src-tauri/migrations:
 *
 *   node scripts/extract-migrations.mjs
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const migrationsDir = `${root}src-tauri/migrations`;
const outputPath = `${root}src/lib/browser/migrations.generated.ts`;

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort((left, right) => left.localeCompare(right));

if (files.length === 0) {
  throw new Error(`No .sql migrations found in ${migrationsDir}`);
}

const migrations = files.map((name) => ({
  name: name.replace(/\.sql$/, ""),
  sql: readFileSync(`${migrationsDir}/${name}`, "utf8").trim(),
}));

const body = migrations
  .map(
    (migration) =>
      `  {\n    name: ${JSON.stringify(migration.name)},\n    sql: ${JSON.stringify(migration.sql)},\n  },`,
  )
  .join("\n");

const output = `// Generated by scripts/extract-migrations.mjs — do not edit by hand.
// Source: src-tauri/migrations (*.sql, ${migrations.length} migration${
  migrations.length === 1 ? "" : "s"
}).
import type { BrowserMigration } from "./migrations";

export const GENERATED_MIGRATIONS: BrowserMigration[] = [
${body}
];
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output, "utf8");
console.log(
  `Extracted ${migrations.length} migration${
    migrations.length === 1 ? "" : "s"
  } into src/lib/browser/migrations.generated.ts`,
);
